export const INDICATOR_MAP: Record<string, Indicator> = Object.fromEntries(INDICATORS.map((i) => [i.id, i]));

export function getIndicator(id: string): Indicator {
  const i = INDICATOR_MAP[id];
  if (!i) throw new Error(`Unknown indicator ${id}`);
  return i;
}

export function formatValue(id: string, v: number | undefined): string {
  if (v === undefined || Number.isNaN(v)) return "—";
  const ind = getIndicator(id);
  return v.toFixed(ind.decimals);
}
